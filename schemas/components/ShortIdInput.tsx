import { useEffect, useRef, useState } from 'react'
import { set, useClient, useFormValue } from 'sanity'
import type { StringInputProps } from 'sanity'

const PREFIX_MAP: Record<string, string> = {
  insight: 'a',
  caseStudy: 'cs',
  experience: 'ex',
}

export function ShortIdInput(props: StringInputProps) {
  const { value, onChange, readOnly } = props
  const client = useClient({ apiVersion: '2024-01-01' })
  const docType = useFormValue(['_type']) as string
  const [loading, setLoading] = useState(false)
  const hasAutoGenerated = useRef(false)

  async function generate() {
    const prefix = PREFIX_MAP[docType]
    if (!prefix) return
    setLoading(true)
    try {
      const results = await client.fetch<{ shortId: string }[]>(
        `*[_type == $type && defined(shortId)] { shortId }`,
        { type: docType }
      )
      const nums = results
        .map((r) => parseInt(r.shortId.replace(/^[a-z]+/, ''), 10))
        .filter((n) => !isNaN(n))
      const next = nums.length > 0 ? Math.max(...nums) + 1 : 1
      const nextId = `${prefix}${String(next).padStart(3, '0')}`
      onChange(set(nextId))
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    if (!value && !hasAutoGenerated.current) {
      hasAutoGenerated.current = true
      generate()
    }
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  return (
    <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
      <div style={{ flex: 1 }}>{props.renderDefault(props)}</div>
      {!readOnly && (
        <button
          type="button"
          onClick={generate}
          disabled={loading}
          style={{
            padding: '6px 12px',
            fontSize: 12,
            cursor: loading ? 'not-allowed' : 'pointer',
            background: '#1a1a1a',
            color: '#fff',
            border: 'none',
            borderRadius: 4,
            whiteSpace: 'nowrap',
            opacity: loading ? 0.6 : 1,
          }}
        >
          {loading ? 'Generating...' : 'Auto-generate'}
        </button>
      )}
    </div>
  )
}
